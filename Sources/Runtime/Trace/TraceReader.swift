import Foundation
import GestureCore

public struct Trace: Sendable {
    public var header: TraceHeader?
    public var records: [TraceRecord]

    public init(header: TraceHeader?, records: [TraceRecord]) {
        self.header = header
        self.records = records
    }

    public var frames: [(t: Double, frame: TouchFrame)] {
        records.compactMap { if case .frame(let f, let t) = $0 { (t, f) } else { nil } }
    }
}

public enum TraceRecord: Sendable {
    case frame(TouchFrame, t: Double)
    case flag(Bool, t: Double)
    case route(GestureRoute, t: Double)
    case config(EngineConfig, t: Double)
    case sys(qos: String, precedence: Int, timeConstraint: Bool)
    case note(String, t: Double)
    /// An abort the hot loop applied before the next frame (losing the game, sleep, a stall).
    case reset(ResetRequest, t: Double)
    /// out, state, inj, gate: regenerated by replay or informational.
    case other(kind: String, t: Double)
}

public enum TraceReaderError: Error, Sendable, Equatable {
    case badLine(Int, String)
}

public enum TraceReader {
    public static func read(_ url: URL) throws -> Trace {
        let text = try String(contentsOf: url, encoding: .utf8)
        return try parse(text)
    }

    public static func parse(_ text: String) throws -> Trace {
        var header: TraceHeader? = nil
        var records: [TraceRecord] = []
        let decoder = JSONDecoder()
        for (number, raw) in text.split(separator: "\n", omittingEmptySubsequences: true).enumerated() {
            let data = Data(raw.utf8)
            guard let obj = try JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let kind = obj["k"] as? String else { throw TraceReaderError.badLine(number + 1, "not an object with k") }
            let t = (obj["t"] as? Double) ?? 0
            switch kind {
            case "header":
                header = try decoder.decode(TraceHeader.self, from: data)
            case "frame":
                records.append(.frame(try frame(obj, t: t, t0: header?.t0Nanos ?? 0, line: number + 1), t: t))
            case "flag":
                records.append(.flag((obj["targetActive"] as? Bool) ?? false, t: t))
            case "route":
                records.append(.route(GestureRoute(traceName: (obj["route"] as? String) ?? "drive"), t: t))
            case "cfg":
                guard let cfg = obj["config"] else { throw TraceReaderError.badLine(number + 1, "cfg without config") }
                let cfgData = try JSONSerialization.data(withJSONObject: cfg)
                records.append(.config(try decoder.decode(EngineConfig.self, from: cfgData), t: t))
            case "sys":
                records.append(.sys(qos: (obj["callbackQoS"] as? String) ?? "unknown",
                                    precedence: (obj["precedence"] as? Int) ?? -1,
                                    timeConstraint: (obj["timeConstraint"] as? Bool) ?? false))
            case "note":
                records.append(.note((obj["msg"] as? String) ?? "", t: t))
            case "reset":
                let request: ResetRequest = (obj["req"] as? String) == "abortAndForget" ? .abortAndForget : .abort
                records.append(.reset(request, t: t))
            default:
                records.append(.other(kind: kind, t: t))
            }
        }
        return Trace(header: header, records: records)
    }

    private static func frame(_ obj: [String: Any], t: Double, t0: UInt64, line: Int) throws -> TouchFrame {
        let entry = UInt64(bitPattern: Int64(bitPattern: t0) &+ Int64((t * 1e9).rounded()))
        var f = TouchFrame(sequence: Int32(truncatingIfNeeded: (obj["seq"] as? Int) ?? 0),
                           entryNanos: entry, deviceTimestamp: (obj["dev"] as? Double) ?? 0)
        for item in (obj["c"] as? [[Double]]) ?? [] {
            guard item.count >= 12, let phase = ContactPhase(rawValue: UInt8(clamping: Int(item[1]))) else {
                throw TraceReaderError.badLine(line, "bad contact")
            }
            f.append(Contact(id: Int32(item[0]), phase: phase,
                             positionMM: SIMD2(Float(item[2]), Float(item[3])),
                             velocityMM: SIMD2(Float(item[4]), Float(item[5])),
                             normalized: SIMD2(Float(item[6]), Float(item[7])),
                             size: Float(item[8]), majorAxisMM: Float(item[9]), minorAxisMM: Float(item[10]),
                             angle: Float(item[11])))
        }
        return f
    }
}
